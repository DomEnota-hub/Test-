package ru.railbrake.calculator.core

data class KnowledgeSource(
    val title: String,
    val note: String? = null,
    val externalUrl: String? = null
)

data class KnowledgeArticle(
    val id: String,
    val title: String,
    val category: String,
    val status: String,
    val summary: String,
    val body: List<String>,
    val tags: List<String>,
    val source: KnowledgeSource,
    val hasInteractiveDiagram: Boolean = false,
    val hasAirRoute: Boolean = false,
    val hasPneumaticSimulator: Boolean = false,
    val hasElectricalSimulator: Boolean = false,
    val relatedArticleIds: List<String> = emptyList()
)

data class AirRouteStep(
    val title: String,
    val description: String
)

data class AirRoute(
    val title: String,
    val start: String,
    val note: String,
    val steps: List<AirRouteStep>
)

enum class PneumaticMode(val title: String) {
    CHARGING("Зарядка"),
    SERVICE_BRAKE("Служебное"),
    RELEASE("Отпуск"),
    AUXILIARY_BRAKE("Вспомогательное")
}

data class PneumaticScenario(
    val mode: PneumaticMode,
    val summary: String,
    val start: String,
    val steps: List<AirRouteStep>
)

data class DiagramHotspot(
    val id: String,
    val title: String,
    val subtitle: String,
    val details: String,
    val learnMore: List<String> = emptyList(),
    val left: Float,
    val top: Float,
    val right: Float,
    val bottom: Float
) {
    fun contains(x: Float, y: Float): Boolean = x in left..right && y in top..bottom
}

