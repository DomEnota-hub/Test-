package ru.railbrake.calculator.core

data class LocomotiveSpec(
    val name: String,
    val category: String,
    val massTons: Double,
    val axles: Int,
    val note: String = "",
    val massKind: String = "Справочная масса; вид массы зависит от источника и исполнения",
    val sourceNote: String = "Учебная справочная база; для расчёта предпочтительны фактические данные машины"
)

data class ConsistItem(
    val locomotive: LocomotiveSpec,
    val quantity: Int
) {
    val totalMassTons: Double get() = locomotive.massTons * quantity
    val totalAxles: Int get() = locomotive.axles * quantity
}

