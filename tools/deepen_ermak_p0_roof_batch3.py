TARGET_IDS = tuple(ROUTES)


def transform(root: dict) -> dict:
    root = deepcopy(root)
    scenarios = {s["id"]: s for s in root.get("scenarios", [])}
    missing = sorted(set(TARGET_IDS) - set(scenarios))
    if missing:
        raise SystemExit(f"Missing target scenarios: {missing}")
    for scenario_id, route in ROUTES.items():
        scenario = scenarios[scenario_id]
        apply_route(scenario, **route)
        notes = list(scenario.get("notes", []))
        note = (
            "2026-09 source revalidation: действующее распоряжение №996/р (ред. №592/р) идентифицировано как замена 671р; "
            "до получения точного текста профильного пункта старые ручные/шунтирующие действия не выдаются пользователю."
        )
        if note not in notes:
            notes.append(note)
        scenario["notes"] = notes
        if scenario_id in {"ER-DIAG-002", "ER-DIAG-030"}:
            scenario["sourceAgeNote"] = (
                "671р от 31.03.2010 утратило роль действующего порядка после введения №996/р с 01.05.2022. "
                "Старый материал используется только как технический указатель причин; пользовательские действия требуют точной сверки с №996/р ред. №592/р и профилем."
            )
    return root


def main() -> None:
    app = load(APP_ASSET)
    patch = load(PATCH_ASSET)
    if app != patch:
        raise SystemExit("app/patch Ermak diagnostic assets differ before transformation")
    transformed = transform(app)
    if len(transformed.get("scenarios", [])) != 136:
        raise SystemExit("Ermak scenario count changed")
    dump(APP_ASSET, transformed)
    dump(PATCH_ASSET, transformed)
    if APP_ASSET.read_bytes() != PATCH_ASSET.read_bytes():
        raise SystemExit("app/patch Ermak diagnostic assets differ after transformation")
    print("ERMAK_P0_ROOF_BATCH3=" + ",".join(sorted(TARGET_IDS)))


if __name__ == "__main__":
    main()
