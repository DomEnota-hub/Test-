def q(node_id: str, prompt: str, choices: list[tuple[str, str]]) -> dict:
    return {
        "id": node_id,
        "type": "question",
        "prompt": prompt,
        "choices": [{"label": label, "nextNodeId": next_id} for label, next_id in choices],
    }

def finding(node_id: str, text: str, next_id: str = "reassess") -> dict:
    return {"id": node_id, "type": "finding", "text": text, "nextNodeId": next_id}

def info(node_id: str, text: str, next_id: str = "reassess") -> dict:
    return {"id": node_id, "type": "info", "text": text, "nextNodeId": next_id}

def terminal(node_id: str, result: str, status: str) -> dict:
    return {"id": node_id, "type": "terminal", "result": result, "terminalStatus": status}

def ui_question(node: dict) -> dict:
    choices = node.get("choices", [])
    out = {"key": node["id"], "text": node["prompt"]}
    if len(choices) > 0:
        out["yesMeaning"] = choices[0]["label"]
        out["yesNextKey"] = choices[0]["nextNodeId"]
    if len(choices) > 1:
        out["noMeaning"] = choices[1]["label"]
        out["noNextKey"] = choices[1]["nextNodeId"]
    if len(choices) > 2:
        out["unknownMeaning"] = choices[2]["label"]
        out["unknownNextKey"] = choices[2]["nextNodeId"]
    return out

def apply_route(
    scenario: dict,
    *,
    nodes: list[dict],
    immediate: list[str],
    causes: list[str],
    checks: list[dict],
    prohibited: list[str],
    related: list[str],
) -> None:
    node_ids = {n["id"] for n in nodes}
    if len(node_ids) != len(nodes):
        raise SystemExit(f"{scenario['id']}: duplicate node ids")
    for node in nodes:
        if node.get("nextNodeId") and node["nextNodeId"] not in node_ids:
            raise SystemExit(f"{scenario['id']}: missing next {node['nextNodeId']}")
        for choice in node.get("choices", []):
            if choice["nextNodeId"] not in node_ids:
                raise SystemExit(f"{scenario['id']}: missing choice target {choice['nextNodeId']}")
    scenario["graph"] = {"startNodeId": "start", "nodes": nodes}
    scenario["relatedScenarioIds"] = sorted(set(scenario.get("relatedScenarioIds", [])) | set(related))
    projection = scenario.setdefault("vl80sUiProjection", {})
    projection["immediateActions"] = immediate
    projection["questions"] = [ui_question(n) for n in nodes if n.get("type") == "question"]
    projection["probableCauses"] = causes
    projection["checks"] = checks
    projection["prohibited"] = prohibited
    projection["relatedScenarioIds"] = scenario["relatedScenarioIds"]
    projection["informationConfidence"] = scenario.get("informationConfidence", projection.get("informationConfidence", ""))

