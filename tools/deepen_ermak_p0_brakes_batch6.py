def transform(data: dict) -> dict:
    scenarios = data.get("scenarios", [])
    by_id = {s["id"]: s for s in scenarios}
    missing = sorted(set(ROUTES) - set(by_id))
    if missing:
        raise SystemExit(f"missing scenarios: {missing}")
    generic = "Отказ локальный (одна секция/узел) или общий?"
    before = sum(
        any(n.get("prompt") == generic for n in by_id[sid].get("graph", {}).get("nodes", []))
        for sid in ROUTES
    )
    print(f"ERMAK_BATCH6_TARGET_GENERIC_BEFORE={before}")
    for sid, route in ROUTES.items():
        apply_route(by_id[sid], **route)
    return data


def main() -> None:
    app = load(APP_ASSET)
    patch = load(PATCH_ASSET)
    if app != patch:
        raise SystemExit("app/patch Ermak diagnostic assets differ before transformation")
    transformed = transform(app)
    if len(transformed.get("scenarios", [])) != 136:
        raise SystemExit("Ermak scenario count changed")
    dump(APP_ASSET, transformed)
    dump(PATCH_ASSET, transformed)
    if APP_ASSET.read_bytes() != PATCH_ASSET.read_bytes():
        raise SystemExit("app/patch Ermak diagnostic assets differ after transformation")
    print("ERMAK_P0_BRAKES_BATCH6=" + ",".join(sorted(ROUTES)))


if __name__ == "__main__":
    main()
