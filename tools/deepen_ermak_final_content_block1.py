def load(path: Path) -> dict:
    with gzip.open(path, 'rt', encoding='utf-8') as f:
        return json.load(f)


def dump(path: Path, data: dict) -> None:
    raw = json.dumps(data, ensure_ascii=False, separators=(',', ':')).encode('utf-8')
    with path.open('wb') as f:
        with gzip.GzipFile(filename='', mode='wb', fileobj=f, mtime=0) as z:
            z.write(raw)


def q(node_id: str, prompt: str, choices: list[tuple[str,str]]) -> dict:
    return {'id':node_id,'type':'question','prompt':prompt,'choices':[{'label':a,'nextNodeId':b} for a,b in choices]}


def finding(node_id: str, text: str, next_id: str) -> dict:
    return {'id':node_id,'type':'finding','text':text,'nextNodeId':next_id}


def info(node_id: str, text: str, next_id: str) -> dict:
    return {'id':node_id,'type':'info','text':text,'nextNodeId':next_id}


def terminal(node_id: str, result: str, status: str) -> dict:
    return {'id':node_id,'type':'terminal','result':result,'terminalStatus':status}


def addref(s: dict, ref: dict) -> None:
    refs = s.setdefault('sourceRefs', [])
    refs[:] = [r for r in refs if r.get('sourceId') != ref['sourceId']]
    refs.append(deepcopy(ref))


def check(title: str, action: str, expected: str, abnormal: str, level: str='CAB') -> dict:
    return {'title':title,'action':action,'expected':expected,'ifAbnormal':abnormal,'level':level}


def ui_questions(nodes: list[dict]) -> list[dict]:
    out=[]
    for n in nodes:
        if n.get('type') != 'question':
            continue
        c=n.get('choices',[])
        item={'key':n['id'],'text':n['prompt']}
        if c:
            item['yesMeaning']=c[0]['label']; item['yesNextKey']=c[0]['nextNodeId']
        if len(c)>1:
            item['noMeaning']=c[1]['label']; item['noNextKey']=c[1]['nextNodeId']
        if len(c)>2:
            item['unknownMeaning']=c[2]['label']; item['unknownNextKey']=c[2]['nextNodeId']
        out.append(item)
    return out


def reachable(nodes: list[dict], start='start') -> set[str]:
    by={n['id']:n for n in nodes}; seen=set(); stack=[start]
    while stack:
        x=stack.pop()
        if x in seen: continue
        if x not in by: raise SystemExit(f'missing graph target {x}')
        seen.add(x); n=by[x]
        if n.get('nextNodeId'): stack.append(n['nextNodeId'])
        stack.extend(c['nextNodeId'] for c in n.get('choices',[]))
    return seen


def apply_route(s: dict, nodes: list[dict], immediate: list[str], causes: list[str], checks: list[dict], prohibited: list[str], refs: list[dict], related: list[str]) -> None:
    ids=[n['id'] for n in nodes]
    if len(ids) != len(set(ids)): raise SystemExit(f"{s['id']}: duplicate node ids")
    seen=reachable(nodes)
    missing=set(ids)-seen
    if missing:
        raise SystemExit(f"{s['id']}: unreachable nodes {sorted(missing)}")
    s['graph']={'startNodeId':'start','nodes':nodes}
    s['relatedScenarioIds']=sorted(set(s.get('relatedScenarioIds',[])) | set(related))
    for r in refs: addref(s,r)
    s['sourceAudit']={'auditedAt':V,'scope':'final_content_completion','status':'IMPROVE'}
    s['sourceAgeNote']='Финальный предметный аудит 27.09.2026: действующие нормы отделены от заводской технической базы; обозначения раннего исполнения не переносятся на поздние профили без подтверждения.'
    actions=s.setdefault('actions',[])
    if not actions: actions.append({})
    actions[0].update({'summary':'Зафиксировать фактический признак и локализовать отказ без ремонтного вмешательства; дальнейшие действия только по подтверждённому профилю и source-bound документу.','sourceBound':False,'riskClass':'normal','userFacingPolicy':'TRIAGE_ONLY_NO_REPAIR'})
    p=s.setdefault('vl80sUiProjection',{})
    p['immediateActions']=immediate
    p['questions']=ui_questions(nodes)
    p['probableCauses']=causes
    p['checks']=checks
